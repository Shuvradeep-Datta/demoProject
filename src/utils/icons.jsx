// Generic icon-by-name renderer. Falls back to a dot if unknown.
export function Icon({ name, size = 16, ...rest }) {
  const Cmp = icons[name] || Circle
  return <Cmp size={size} {...rest} />
}

// Pick a file icon + color based on extension.
export function FileIcon({ name, size = 16 }) {
  if (name.endsWith('.json')) return <FileJson size={size} color="#cbcb41" />
  if (name.endsWith('.md')) return <FileText size={size} color="#519aba" />
  if (name.endsWith('.jsx') || name.endsWith('.js')) return <FileCode2 size={size} color="#f1e05a" />
  return <FileText size={size} color="#9aa0a6" />
}
